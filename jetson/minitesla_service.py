#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""安裝及管理智慧車的 systemd 服務；以原本的 Python 環境執行。"""
import argparse
import importlib.util
import os
from pathlib import Path
import pwd
import shutil
import stat
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parent
TARGET = "minitesla.target"
SERVICES = ("minitesla-vehicle.service", "minitesla-lidar.service",
            "minitesla-recorder.service")
UNITS = (TARGET,) + SERVICES
UNIT_DIR = Path("/etc/systemd/system")
SEARCH_DIRS = (UNIT_DIR, Path("/run/systemd/system"),
               Path("/usr/lib/systemd/system"), Path("/lib/systemd/system"))
MARKER = "# Generated by MiniTesla Phase 7; managed uid="


def checked_text(value):
    value = str(value)
    if any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise ValueError("路徑或設定不得包含換行、NUL 或其他控制字元。")
    return value


def quote(value, command=False):
    """systemd 雙引號字串；ExecStart 的 $ 與所有設定的 % 分別跳脫。"""
    value = checked_text(value).replace("\\", "\\\\").replace('"', '\\"')
    value = value.replace("%", "%%")
    if command:
        value = value.replace("$", "$$")
    return '"' + value + '"'


def exec_line(argv):
    return "ExecStart=" + " ".join(quote(part, command=True) for part in argv)


def runtime_config(project, config_path, pc_host):
    """由車端既有解析器處理設定，避免服務與手動啟動的設定解讀不同。"""
    sys.path.insert(0, str(project))
    try:
        spec = importlib.util.spec_from_file_location(
            "_minitesla_service_vehicle", project / "minitesla.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module.load_config(argv=["--config", str(config_path),
                                        "--pc-host", pc_host, "--no-display"])
    finally:
        sys.path.pop(0)


def environment_lines(environ):
    # 不複製整份 shell 環境；保留既有 Python/CUDA 路徑，不保存 token 或 DISPLAY。
    lines = ["Environment=PYTHONUNBUFFERED=1"]
    for key in ("PATH", "LD_LIBRARY_PATH", "PYTHONPATH"):
        if key in environ:
            lines.append("Environment=" + quote(key + "=" + environ[key]))
    return lines


def render_units(project, python, account, config_path, config, lidar_binary,
                 lidar_device, environ):
    marker = MARKER + str(account.pw_uid)
    pc_host = checked_text(config["network"]["pc_host"])
    working_directory = checked_text(project)
    if working_directory != working_directory.strip() or working_directory.endswith("\\"):
        raise ValueError("專案路徑的開頭或結尾不得是空白字元，結尾也不得是反斜線。")
    common = [marker, "[Unit]", "PartOf=" + TARGET,
              "StartLimitIntervalSec=0", "[Service]", "Type=simple",
              "User=" + checked_text(account.pw_name),
              "Group=" + str(account.pw_gid),
              # WorkingDirectory= 是單一原始路徑，不使用 ExecStart 的引號解析。
              "WorkingDirectory=" + working_directory.replace("%", "%%"), "UMask=0077",
              "Restart=always", "RestartSec=3", "TimeoutStopSec=15",
              "StandardError=journal"] + environment_lines(environ)
    commands = {
        SERVICES[0]: [python, "-u", str(project / "minitesla.py"),
                      "--config", str(config_path), "--pc-host", pc_host,
                      "--no-display"],
        SERVICES[1]: [str(lidar_binary), "--channel", "--serial", lidar_device,
                      "460800"],
        SERVICES[2]: [python, "-u", str(project / "demo_recorder.py"), "record",
                      "--snapshot", config["snapshot"]["path"],
                      "--output-dir", str(project / "demo_records")],
    }
    result = {
        TARGET: "\n".join([marker, "[Unit]", "Description=智慧車服務",
                            "Wants=" + " ".join(SERVICES),
                            "After=network-online.target",
                            "Wants=network-online.target", "[Install]",
                            "WantedBy=multi-user.target", ""])
    }
    for name, command in commands.items():
        lines = common[:]
        # Target ordering alone does not order its Wants= services after the network.
        lines[2:2] = ["Description=" + name[:-8],
                      "After=network-online.target", "Wants=network-online.target"]
        if name == SERVICES[0]:
            lines += ["KillSignal=SIGINT", "KillMode=mixed", "StandardOutput=journal"]
        elif name == SERVICES[1]:
            # 原 SDK 將每個量測點印至 stdout；避免 journal 被雷達點雲塞滿。
            lines += ["KillSignal=SIGINT", "KillMode=control-group", "StandardOutput=null"]
        else:
            lines += ["KillSignal=SIGTERM", "KillMode=control-group", "StandardOutput=journal"]
        lines += [exec_line(command), ""]
        result[name] = "\n".join(lines)
    return result


def inspect_ownership(uid, require_installed=False, unit_dir=UNIT_DIR,
                      search_dirs=SEARCH_DIRS):
    """拒絕同名的非本工具服務、符號連結及個別服務的外部覆寫。"""
    expected = MARKER + str(uid)
    existing = []
    for name in UNITS:
        installed = unit_dir / name
        for directory in search_dirs:
            drop_in = directory / (name + ".d")
            if drop_in.exists() and any(drop_in.glob("*.conf")):
                raise RuntimeError("發現外部服務覆寫：{}；請先自行處理。".format(drop_in))
            candidate = directory / name
            if candidate == installed or not candidate.exists():
                continue
            raise RuntimeError("已有同名系統服務：{}；未覆蓋。".format(candidate))
        if installed.is_symlink():
            raise RuntimeError("服務檔是符號連結，未修改：{}".format(installed))
        if installed.exists():
            if not installed.is_file():
                raise RuntimeError("服務路徑不是一般檔案：{}".format(installed))
            first_line = installed.read_text(encoding="utf-8").splitlines()[:1]
            if first_line != [expected]:
                raise RuntimeError("不是這個使用者安裝的智慧車服務，未修改：{}".format(installed))
            existing.append(name)
    if require_installed and set(existing) != set(UNITS):
        raise RuntimeError("智慧車服務尚未完整安裝；請先執行 install。")
    return existing


def check_output_directory(path):
    """允許程式建立子資料夾，先確認最近的既有上層可寫入。"""
    original = Path(path)
    current = original
    while not current.exists() and not current.is_symlink() and current != current.parent:
        current = current.parent
    if not current.is_dir() or not os.access(current, os.W_OK | os.X_OK):
        raise RuntimeError("輸出資料夾無法建立或寫入：{}".format(original))


def check_instance_available(project):
    sys.path.insert(0, str(project))
    try:
        from minitesla_sensors.runtime import SingleInstance
        with SingleInstance():
            pass
    finally:
        sys.path.pop(0)


def preflight(project, python, config, lidar_binary, lidar_device):
    for path in (project / "minitesla.py", project / "demo_recorder.py",
                 Path(config["camera"]["model"]), lidar_binary):
        if not path.is_file():
            raise RuntimeError("找不到必要檔案：{}".format(path))
    if not os.access(lidar_binary, os.X_OK):
        raise RuntimeError("雷達 SDK 程式無法執行：{}".format(lidar_binary))
    network = config["network"]
    if network.get("lidar_local_host") != "127.0.0.1" or int(network.get("lidar_local_port", 0)) != 6000:
        raise RuntimeError("目前雷達 SDK 固定傳送至 127.0.0.1:6000；請維持相同的 lidar_local 設定。")
    # 先快速拒絕既有車端程式，避免等完 Torch 匯入才發現必須先停止服務。
    check_instance_available(project)
    for label, device in (("M4", config["uart"]["device"]), ("雷達", lidar_device),
                          ("相機", "/dev/video{}".format(config["camera"]["index"]))):
        path = Path(device)
        if not path.exists() or not stat.S_ISCHR(path.stat().st_mode):
            raise RuntimeError("{} 裝置不存在或不是字元裝置：{}".format(label, path))
        if not os.access(path, os.R_OK | os.W_OK):
            raise RuntimeError("目前使用者沒有 {} 讀寫權限：{}；請沿用原本可操作裝置的帳號。".format(label, path))
    for path in (Path(config["snapshot"]["path"]).parent, project / "demo_records"):
        check_output_directory(path)
    # 只檢查匯入，不重新安裝套件、不開啟相機或載入模型。
    subprocess.run([python, "-c", "import serial, cv2, numpy, torch, torchvision, ultralytics"],
                   cwd=str(project), check=True, timeout=120)


def privileged(argv):
    sudo = shutil.which("sudo")
    if not sudo:
        raise RuntimeError("找不到 sudo；請在 Jetson 一般使用者帳號下執行。")
    subprocess.run([sudo, "--"] + list(argv), check=True)


def systemctl_args(*args):
    executable = shutil.which("systemctl")
    if not executable:
        raise RuntimeError("找不到 systemctl；此工具用於 Jetson 的 systemd 系統。")
    return [executable] + list(args)


def validate_units(units, directory):
    for name, content in units.items():
        (directory / name).write_text(content, encoding="utf-8")
    validator = shutil.which("systemd-analyze")
    if not validator:
        raise RuntimeError("找不到 systemd-analyze，尚未安裝任何服務。")
    subprocess.run([validator, "verify"] + [str(directory / name) for name in UNITS],
                   check=True)


def install(units, uid, project, python, config, lidar_binary, lidar_device):
    existing = inspect_ownership(uid)
    preflight(project, python, config, lidar_binary, lidar_device)
    with tempfile.TemporaryDirectory(prefix="minitesla-units-") as scratch:
        staging = Path(scratch)
        validate_units(units, staging)
        # 若上次安裝不完整，先停止這個使用者的剩餘服務；不接觸其他程式。
        if existing:
            privileged(systemctl_args("stop", *existing))
        copier = shutil.which("install")
        if not copier:
            raise RuntimeError("找不到 install 指令。")
        for name in UNITS:
            privileged([copier, "-o", "root", "-g", "root", "-m", "0644",
                        "--", str(staging / name), str(UNIT_DIR / name)])
        privileged(systemctl_args("daemon-reload"))
        privileged(systemctl_args("enable", "--now", TARGET))
        privileged(systemctl_args("start", *SERVICES))
    print("已安裝並啟動；往後開機自動進入待命，不自動選擇行駛模式。")
    print("Python：{}\n專案：{}".format(python, project))
    print("查看狀態：python3 minitesla_service.py status")


def manage(action, uid):
    existing = inspect_ownership(uid, require_installed=(action != "uninstall"))
    if action == "status":
        return subprocess.run(systemctl_args("status", "--no-pager", "--full", *UNITS)).returncode
    if action == "logs":
        journal = shutil.which("journalctl")
        if not journal:
            raise RuntimeError("找不到 journalctl。")
        privileged([journal, "--no-pager", "-n", "150", "-f"] +
                   [part for name in SERVICES for part in ("-u", name)])
    elif action in ("start", "stop", "restart"):
        privileged(systemctl_args(action, *UNITS))
    elif action == "disable":
        privileged(systemctl_args("stop", *UNITS))
        privileged(systemctl_args("disable", TARGET))
        print("已停止全部服務並取消開機啟動；start 仍可手動啟動。")
    elif action == "uninstall":
        if not existing:
            print("沒有本工具安裝的服務檔。")
            return 0
        privileged(systemctl_args("stop", *existing))
        if TARGET in existing:
            privileged(systemctl_args("disable", TARGET))
        remover = shutil.which("rm")
        if not remover:
            raise RuntimeError("找不到 rm 指令。")
        privileged([remover, "--"] + [str(UNIT_DIR / name) for name in existing])
        privileged(systemctl_args("daemon-reload"))
        print("已移除本工具產生的四個服務檔；專案程式及執行紀錄保留。")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("install", "start", "stop", "restart", "status",
                                           "logs", "disable", "uninstall"))
    parser.add_argument("--pc-host", default="120.126.10.41")
    parser.add_argument("--config", default=str(ROOT / "sensor_config.json"))
    parser.add_argument("--lidar-device", default="/dev/ttyUSB0")
    parser.add_argument("--lidar-binary", default=str(ROOT / "rplidar_sdk-master" /
                                                     "output/Linux/Release/ultra_simple"))
    parser.add_argument("--dry-run", action="store_true",
                        help="只列出四個服務檔；不檢查硬體、不取得 sudo、不安裝")
    args = parser.parse_args(argv)
    if args.dry_run and args.action != "install":
        parser.error("--dry-run 僅供 install 使用。")
    if not sys.platform.startswith("linux"):
        parser.error("此工具只支援 Linux／Jetson。")
    if os.geteuid() == 0 and not args.dry_run:
        parser.error("請先啟用原本的 Python 環境，再以一般使用者執行；不要使用 sudo python3。")
    account = pwd.getpwuid(os.getuid())
    try:
        if args.action != "install":
            return manage(args.action, account.pw_uid)
        config_path = Path(args.config).expanduser().resolve()
        lidar_binary = Path(args.lidar_binary).expanduser().resolve()
        lidar_device = checked_text(args.lidar_device)
        # abspath 不解析 venv 的 Python symlink；保留使用者選定的環境。
        python = os.path.abspath(sys.executable)
        config = runtime_config(ROOT, config_path, checked_text(args.pc_host))
        units = render_units(ROOT, python, account, config_path, config,
                             lidar_binary, lidar_device, os.environ)
        if args.dry_run:
            for name, content in units.items():
                print("# ===== {} =====\n{}".format(name, content))
            return 0
        install(units, account.pw_uid, ROOT, python, config, lidar_binary, lidar_device)
        return 0
    except KeyboardInterrupt:
        print("\n已中止操作；可執行 status 查看目前服務狀態。", file=sys.stderr)
        return 130
    except (OSError, ValueError, RuntimeError, ImportError, subprocess.SubprocessError) as exc:
        print("操作未完成：{}".format(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
